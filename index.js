function fillSpaces(text) {
    text = text
        .replace(/\t/g, " ")
        .replace(/^\n/, "")
        .replace(/\n\s*$/, "");

    const lines = text.split("\n");

    const width = Math.max(
        ...lines.map(line => line.length)
    );

    return lines
        .map(line => line.padEnd(width, " "))
        .join("\n");
}

function addBorder(text, fillSpacesEnabled = true, border = {
    top: "━",
    bottom: "━",
    left: "┃",
    right: "┃",
    topLeft: "┏",
    topRight: "┓",
    bottomLeft: "┗",
    bottomRight: "┛"
}) {
    if (fillSpacesEnabled) {
        text = fillSpaces(text);
    }

    const lines = text.split("\n");

    const width = Math.max(
        ...lines.map(line => line.length)
    );

    const top =
        border.topLeft +
        border.top.repeat(width) +
        border.topRight;

    const bottom =
        border.bottomLeft +
        border.bottom.repeat(width) +
        border.bottomRight;

    const body = lines.map(line =>
        border.left + line + border.right
    );

    return [
        top,
        ...body,
        bottom
    ].join("\n");
}

function animateASCII(element, icon, duration = 2000) {
    const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789@#$%&*";

    const target = icon

    const length = target.length;

    // Случайный порядок символов, которые будут фиксироваться
    const order = [...target]
        .map((char, index) => ({ char, index }))
        .filter(({ char }) => char !== "\n")
        .map(({ index }) => index)
        .sort(() => Math.random() - 0.5);

    const start = performance.now();

    function randomChar() {
        return chars[Math.floor(Math.random() * chars.length)];
    }

    function random_frame(time) {
        const progress = Math.min(
            (time - start) / duration,
            1
        );

        const count = Math.floor(
            order.length * progress
        );

        const fixed = new Set(
            order.slice(0, count)
        );

        const result = [...target]
            .map((char, i) => {
                if (char === "\n") {
                    return "\n";
                }

                return fixed.has(i)
                    ? char
                    : randomChar();
            })
            .join("");

        element.textContent = result;

        if (progress < 1) {
            requestAnimationFrame(random_frame);
        } else {
            element.textContent = target;
        }
    }

    requestAnimationFrame(random_frame);
}
async function addASCIIcon(icon) {
    const element = document.querySelector("#icon .ascii");
    animateASCII(element, addBorder(icon))
}

function applyTheme() {
    const hour = new Date().getHours();
    const isNight = hour < 7 || hour >= 19;

    const language = getUserLanguage();
    const translation = translations[language];

    if (isNight) {
        document.body.classList.add("dark-theme");
        document.getElementById("greeting").textContent =
            translation.greetingWhite;
    } else {
        document.body.classList.remove("dark-theme");
        document.getElementById("greeting").textContent =
            translation.greetingBlack;
    }
}

function getUserLanguage() {
    const language = navigator.language.toLowerCase();

    if (language.startsWith("ru")) {
        return "ru";
    }

    return "en";
}

function applyLocalization() {
    const language = getUserLanguage();
    const translation = translations[language];

    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;

        if (translation[key]) {
            element.textContent = translation[key];
        }
    });
}

